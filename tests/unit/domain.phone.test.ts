import { describe, it, expect } from "vitest";
import { normalizePhone } from "@/lib/domain/phone";

describe("normalizePhone", () => {
  it.each([
    ["010 1234 5678", "010-1234-5678"],
    ["+82 10-1234-5678", "010-1234-5678"],
    ["82 10 1234 5678", "010-1234-5678"],
    ["(010) 1234.5678", "010-1234-5678"],
    ["01012345678", "010-1234-5678"],
    ["02-123-4567", "02-123-4567"],
    ["0212345678", "02-1234-5678"],
    ["+82 2 123 4567", "02-123-4567"],
    ["031-123-4567", "031-123-4567"],
    ["0311234567", "031-123-4567"],
    ["070-1234-5678", "070-1234-5678"],
  ])("%s -> %s", (i, o) => expect(normalizePhone(i)).toBe(o));

  it.each(["12345", "", "abc", "1012345678", "0123456789012", "02-12-345", "010-123-45678-9"])(
    "%s -> null", (i) => expect(normalizePhone(i)).toBeNull());
});
